#!/usr/bin/env bash
# Generate Config/OpenJDKMobile.link.xcconfig from the staged OpenJDK Mobile
# static libraries (device-only link flags for the CoreJ2 app target).
#
# Run after scripts/openjdk-mobile/build-all.sh:
#   ./scripts/openjdk-mobile/generate-xcode-link-xcconfig.sh

set -euo pipefail
# shellcheck source=common.sh
source "$(cd "$(dirname "$0")" && pwd)/common.sh"

STAGED_LINK="${STAGED_ROOT}/current"
[[ -e "${STAGED_LINK}" ]] || ojdk_die "missing ${STAGED_LINK} — run scripts/openjdk-mobile/build-all.sh first"

STATIC_LIBS="${STAGED_LINK}/static-libs"
LIBJVM="${STATIC_LIBS}/lib/zero/libjvm.a"
[[ -f "${LIBJVM}" ]] || ojdk_die "missing ${LIBJVM} — run scripts/openjdk-mobile/build-all.sh first"

# Companion static libraries shipped in the static-libs image.
# libjvm.a is force-loaded so JNI_CreateJavaVM is present for dlsym lookup.
#
# HotSpot resolves JIMAGE_*, JDK_Canonicalize, and ZIP_* only via
# dlsym(RTLD_DEFAULT) when statically linked. Plain -l dead-strips those
# objects → (*JImageOpen) jumps to PC=0 → CODESIGNING Invalid Page.
# Force-load only the libs that are looked up that way; force-loading
# everything (instrument/jdwp/…) pulls iconv and other host-only deps.
COMPANION_LIBS=""
FORCE_LOAD_LIBS=""
for lib in "${STATIC_LIBS}"/lib/*.a; do
  [[ -f "${lib}" ]] || continue
  name="$(basename "${lib}" .a)"
  name="${name#lib}"
  case "${name}" in
    # dlsym / JNI natives that HotSpot and java.base resolve by name only:
    # jimage/java/zip (VM boot), nio (JarFile / UnixNativeDispatcher on iOS),
    # verify (VerifyClassForMajorVersion — else VerifyError "Could not link verifier").
    jimage|java|zip|nio|verify)
      FORCE_LOAD_LIBS="${FORCE_LOAD_LIBS} -Wl,-force_load,\$(COREJ2_OJDK_STAGED)/lib/lib${name}.a"
      ;;
    *)
      COMPANION_LIBS="${COMPANION_LIBS} -l${name}"
      ;;
  esac
done
[[ -n "${COMPANION_LIBS}${FORCE_LOAD_LIBS}" ]] || ojdk_die "no companion libraries found under ${STATIC_LIBS}/lib"

# libffi comes from the Gluon mobile-support bundle (Zero needs it for calls).
LIBFFI="$(find "${OJDK_SUPPORT_EXTRACTED}" -name 'libffi*.a' -type f 2>/dev/null | head -1 || true)"
[[ -n "${LIBFFI}" && -f "${LIBFFI}" ]] || ojdk_die "libffi.a not found under ${OJDK_SUPPORT_EXTRACTED} — run scripts/openjdk-mobile/02-fetch-support.sh"
LIBFFI_REL="${LIBFFI#"${REPO_ROOT}"/}"

OUT="${REPO_ROOT}/Config/OpenJDKMobile.link.xcconfig"
mkdir -p "$(dirname "${OUT}")"
cat > "${OUT}" <<EOF
// Generated by scripts/openjdk-mobile/generate-xcode-link-xcconfig.sh — do not edit by hand.
// Device-only link flags for the embedded OpenJDK Mobile (Zero) JVM.

COREJ2_OJDK_STAGED = \$(SRCROOT)/artifacts/openjdk-mobile/staged/current/static-libs

LIBRARY_SEARCH_PATHS[sdk=iphoneos*] = \$(inherited) \$(COREJ2_OJDK_STAGED)/lib \$(COREJ2_OJDK_STAGED)/lib/zero

OTHER_LDFLAGS[sdk=iphoneos*] = \$(inherited) -Wl,-force_load,\$(COREJ2_OJDK_STAGED)/lib/zero/libjvm.a${FORCE_LOAD_LIBS}${COMPANION_LIBS} \$(SRCROOT)/${LIBFFI_REL} -lc++
EOF

ojdk_log "Wrote ${OUT}"
ojdk_log "Force-loaded (dlsym) libraries:${FORCE_LOAD_LIBS}"
ojdk_log "Companion libraries:${COMPANION_LIBS}"
ojdk_log "libffi: ${LIBFFI_REL}"
